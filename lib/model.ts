// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other pre-token protocol the snapshot carries that passes the rankable rule — the watchlist's
// nature test without its TVL floor: a wrapped, staked or bridged product of a token that already
// trades is not a launch, so Bridge, Liquid Staking and their kin never rank, however large their
// TVL. A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko
// id, no symbol); the snapshot's live-token protocols are kept apart and shown as the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base multiple = the MEDIAN market-cap/TVL ratio of the live-token protocols in this same
//                     snapshot (120 of them on 2026-11-14: median 0.2410). The market's own pricing
//                     of launched tokens, computed at run time — never a hand-picked constant.
//   base       = tvl_usd x base multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   damp       = clamp(sqrt(tvl_usd / 100,000,000), 0.25, 1): a +200% week on $5M of TVL is noise,
//                so small protocols keep only a quarter of their growth term; at $100M+ it counts
//                in full.
//   growthMult = 1 + (growth / 100) x 0.5 x damp
//   maturity   = 0.6 + min(age_days, 1825) / 1825 x 0.6   (age_days unknown: 365)
//                A five-year horizon, not three: a protocol that has run five years with no token
//                is overdue, and the model pays it up to 1.2x instead of topping out at 1.0x.
//   implied    = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row.

